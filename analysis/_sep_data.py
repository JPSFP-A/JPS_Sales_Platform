    out = {}
    for mo in d['months']:
        if mo < '2025-01': continue
        row = {}
        for code in ('NB10', 'NB20', 'NB40'):
            c = k = 0
            for key, par in d['srat'][mo].items():
                if key.split('||')[0] == code:
                    for v in par.values(): c += v[ix['count']]; k += v[ix['kwh']]
            row[code] = (c, k)
        out[mo] = row
    return out
