def demand_ex_alcoa():
    d = json.load(open('corrected.json', encoding='utf-8')); AL = d['acct_legend']; ix = {n: i for i, n in enumerate(AL)}
    out = {}
    for code, a in d['acct'].items():
        t = a['title']
        if t not in ('RT40', 'RT50', 'RT70'): continue
        if a['name'].upper().startswith('ALCOA'): continue
        for m, v in a['m'].items():
            if m < '2025-01' or m > '2026-09': continue
            r = out.setdefault((t, m), [0.0, 0.0, 0])
            r[0] += v[ix['kwh']]; r[1] += v[ix['kva']]; r[2] += 1
