def parish_res():
    d = json.load(open('corrected.json', encoding='utf-8')); L = d['srat_legend']; ix = {n: i for i, n in enumerate(L)}
    norm = lambda s: str(s).strip().upper()
    RMAP = {}; RCMAP = {}
    for r in list(csv.reader(open(r'C:/Users/jwilson/Downloads/Rate categorry Data mapping.csv', encoding='utf-8-sig')))[1:]:
        if len(r) >= 3: RMAP[norm(r[2])] = r[0]; RCMAP.setdefault(norm(r[1]), r[0])
    def title(k):
        s, rc = k.split('||'); return RCMAP.get(norm(rc)) or RMAP.get(norm(s))
    Y25 = ['2025-%02d' % i for i in range(1, 10)]; Y26 = ['2026-%02d' % i for i in range(1, 10)]
    P = {}
    for mo in Y25 + Y26:
        for k, par in d['srat'][mo].items():
            if title(k) != 'RT10': continue
            for p, v in par.items():
                r = P.setdefault(p, dict(c25=0, c26=0, k25=0, k26=0, r25=0, r26=0))
                if mo == '2025-09': r['c25'] += v[ix['count']]
                if mo == '2026-09': r['c26'] += v[ix['count']]
                y = '25' if mo in Y25 else '26'
                r['k' + y] += v[ix['kwh']]; r['r' + y] += v[ix['rev']]
    return P

