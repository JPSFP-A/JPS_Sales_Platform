# ---- residential postpaid components YTD9 (J$M) from the raw-billing cache ----
def res_components():
    ex = json.load(open('_report_extras.json'))['res_components']
    out = {}
    for y in (2025, 2026):
        mons = ['%d-%02d' % (y, m) for m in range(1, 10)]
        out[y] = {k: sum(ex[m][k] for m in mons) / 1e6 for k in ('kwh', 'rev', 'energy', 'fuel', 'ipp', 'cust')}
